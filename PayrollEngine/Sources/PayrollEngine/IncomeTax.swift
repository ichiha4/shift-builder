import Foundation

/// Which withholding column applies to a shift's employer, per the National Tax Agency's
/// 源泉徴収税額表: 甲欄 is the one job a worker has submitted a 扶養控除等申告書 to (normally
/// their main/only job); every other concurrent job is 乙欄, which withholds at a higher,
/// dependents-blind rate. Combining multiple employers' pay before applying a single table —
/// the mistake this type exists to prevent — is not how real withholding works and overstates
/// take-home pay for anyone with more than one job.
public enum IncomeTaxColumn: String, Codable, CaseIterable, Sendable {
    case kou // 甲欄 — main job
    case otsu // 乙欄 — secondary job(s)
}

/// Monthly income-tax (源泉徴収) withholding, reproducing the National Tax Agency's
/// 給与所得の源泉徴収税額表 for the year the salary is PAID in. The table changes by year —
/// 令和8年分 (2026) raised the deductions from 令和7年分, and 令和9年分 (2027) raised them
/// again — and the NTA marks each year's method 「…年分以前の給与等には使用できません」, so the
/// payday's year must pick the table.
///
/// 甲欄 uses the NTA's formula-based 「月額表の甲欄を適用する給与等に対する税額の電算機計算の
/// 特例」 (the method payroll software is explicitly permitted to use in place of reading the
/// printed table). It can differ from the printed table — by up to about ¥140 at typical
/// part-time pay and about ¥320 at high pay — because the table is computed at each row's
/// midpoint and prints 0 below each column's first taxed row; both are lawful, and 年末調整
/// settles either one.
/// 乙欄 uses the printed 月額表 rows (transcribed from the NTA's Excel for each year) and the
/// table's own formulas below and above them.
///
/// Sources: nta.go.jp/publication/pamph/gensen/zeigakuhyo2024 (令和7年分; its 月額表 is
/// identical to 令和3〜6年分), zeigakuhyo2026 (令和8年分), zeigakuhyo2027 (令和9年分).
public enum IncomeTax {
    /// Years whose tables are transcribed here. Earlier years use 令和7年分 and later years use
    /// 令和9年分 — the nearest published table.
    public static let publishedYears = 2025...2027
    /// Years the result is exact for: 令和3〜6年分 (2021–2024) use the same 月額表 as 令和7年分
    /// (verified row for row against the NTA Excel for each year). Callers flag other years as
    /// estimates.
    public static let exactYears = 2021...2027

    /// The year whose table is actually used for a payday in `year`.
    public static func tableYear(for year: Int) -> Int {
        min(max(year, publishedYears.lowerBound), publishedYears.upperBound)
    }

    /// `socialInsurance`: this month's employee-paid health/pension/employment-insurance
    /// premiums for this same employer, to be subtracted before tax per the official method.
    /// `year`: the year of the payday (支給日), which decides the table.
    public static func monthlyWithholding(
        grossPay: Double,
        column: IncomeTaxColumn,
        dependentsCount: Int = 0,
        hasSpouseAllowance: Bool = false,
        socialInsurance: Double = 0,
        year: Int
    ) -> Double {
        // Whole yen first: the tables are keyed on yen amounts, and a pay total built from
        // fractional per-minute pay (e.g. 124,999.9999…) must not fall into the row below.
        let a = max(0, Int((grossPay - socialInsurance).rounded()))
        let rules = Rules.for(tableYear(for: year))
        switch column {
        case .kou: return Double(kouWithholding(a: a, dependentsCount: dependentsCount, hasSpouseAllowance: hasSpouseAllowance, rules: rules))
        case .otsu: return Double(otsuWithholding(a: a, rules: rules))
        }
    }

    // MARK: - Year rules

    private struct Rules {
        /// 別表第一: 給与所得控除 — a fixed minimum up to `minimumUpTo`, then percentage bands.
        let salaryMinimum: Int
        let minimumUpTo: Int
