    // MARK: - 甲欄 (電算機計算の特例)

    /// Integer yen throughout, so the published rounding rules apply exactly: 給与所得控除 is
    /// rounded UP to the yen, and the tax is rounded half-up to 10 yen.
    private static func kouWithholding(a: Int, dependentsCount: Int, hasSpouseAllowance: Bool, rules: Rules) -> Int {
        func percentUp(_ tenths: Int) -> Int { (a * tenths + 9) / 10 }
        let salaryDeduction: Int
        if a <= rules.minimumUpTo {
            salaryDeduction = rules.salaryMinimum
        } else if let band = rules.fortyPercentBand, band.contains(a) {
            salaryDeduction = percentUp(4) - 8_333
        } else if a <= 299_999 {
            salaryDeduction = percentUp(3) + 6_667
        } else if a <= 549_999 {
            salaryDeduction = percentUp(2) + 36_667
        } else if a <= 708_330 {
            salaryDeduction = percentUp(1) + 91_667
        } else {
            salaryDeduction = 162_500
        }

        let spouseDeduction = hasSpouseAllowance ? 31_667 : 0
        let dependentsDeduction = 31_667 * max(0, dependentsCount)

        let basicDeduction: Int
        switch a {
        case ...rules.basicFullUpTo: basicDeduction = rules.basicFull
        case ...2_162_499: basicDeduction = 40_000
        case ...2_204_166: basicDeduction = 26_667
        case ...2_245_833: basicDeduction = 13_334
        default: basicDeduction = 0
        }

        let b = max(0, a - salaryDeduction - spouseDeduction - dependentsDeduction - basicDeduction)

        // 別表第四, in units of 1/100,000 yen: tax = B × rate − subtraction.
        let (rate, subtraction): (Int, Int)
        switch b {
        case ...162_500: (rate, subtraction) = (5_105, 0)
        case ...275_000: (rate, subtraction) = (10_210, 8_296)
        case ...579_166: (rate, subtraction) = (20_420, 36_374)
        case ...750_000: (rate, subtraction) = (23_483, 54_113)
        case ...1_500_000: (rate, subtraction) = (33_693, 130_688)
        case ...3_333_333: (rate, subtraction) = (40_840, 237_893)
        default: (rate, subtraction) = (45_945, 408_061)
        }
        let scaled = b * rate - subtraction * 100_000
        guard scaled > 0 else { return 0 }
        return (scaled + 500_000) / 1_000_000 * 10
    }

    // MARK: - 乙欄

    /// Fractions of a yen are dropped (「求めた税額に１円未満の端数があるときは、これを切り捨て
    /// ます」).
    private static func otsuWithholding(a: Int, rules: Rules) -> Int {
        if a < rules.otsuTableStart {
            return a * 3_063 / 100_000
        }
        if a >= rules.otsuTopFrom {
            return rules.otsuTopBase + (a - rules.otsuTopFrom) * 45_945 / 100_000
        }
        if a >= 740_000 {
            return rules.otsuAt740k + (a - 740_000) * 4_084 / 10_000
        }
        var result = rules.otsuTable[0].tax
        for row in rules.otsuTable where a >= row.from {
            result = row.tax
        }
        return result
    }

