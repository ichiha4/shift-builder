        let otsuTableStart: Int
        let otsuTable: [(from: Int, tax: Int)]
        let otsuAt740k: Int
        let otsuTopFrom: Int
        let otsuTopBase: Int

        static func `for`(_ year: Int) -> Rules {
            switch year {
            case ...2025: return reiwa7
            case 2026: return reiwa8
            default: return reiwa9
            }
        }

